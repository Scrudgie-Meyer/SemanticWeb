def entity(value):
    name, kind = value
    return {'id': kind + '_' + hashlib.sha256(name.encode()).hexdigest()[:16],
            'name': name, 'type': kind}

def main():
    facts = []
    for path in sorted((BASE / 'corpus').glob('*.txt')):
        for sentence in re.split(r'(?<=[.!?])\s+', path.read_text(encoding='utf-8')):
            for connector, relation in relations.items():
                if connector not in sentence:
                    continue
                left, right = sentence.rsplit(connector, 1)
                # Some first sentences have an introductory clause before the explicit fact.
                matches = [s for s in subjects if left.endswith(s)]
                if not matches or right.rstrip('.') not in objects:
                    continue
                subject = max(matches, key=len)
                evidence = subject + connector + right
                facts.append({'doc_id': path.stem, 'subject': entity(subjects[subject]),
                              'relation': relation, 'object': entity(objects[right.rstrip('.')]),
                              'evidence': evidence})
    (BASE / 'reference_facts.json').write_text(json.dumps(facts, ensure_ascii=False, indent=2), encoding='utf-8')
    print(f'{len(facts)} author annotations saved; no LLM was called.')

if __name__ == '__main__':
    main()
